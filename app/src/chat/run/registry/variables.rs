#[allow(clippy::too_many_arguments)]
const fn v(
    name: &'static str,
    syntax: &'static str,
    scope: &'static [&'static str],
    filled: &'static [&'static str],
    chatterino: &'static [&'static str],
    value: &'static str,
    empty: &'static str,
    examples: &'static [Example],
    spec: &'static str,
) -> Variable {
    Variable {
        name,
        syntax,
        scope,
        filled,
        chatterino,
        value,
        empty,
        examples,
        spec,
    }
}

