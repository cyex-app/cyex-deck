//! The variables the command language reads: arguments, the app’s values, 7TV.

use super::language::Variable;
use super::{Example, ex};

const fn v(
    name: &'static str,
    syntax: &'static str,
    scope: &'static [&'static str],
    value: &'static str,
    empty: &'static str,
    examples: &'static [Example],
    spec: &'static str,
) -> Variable {
    Variable {
        name,
        syntax,
        scope,
        value,
        empty,
        examples,
        spec,
    }
}

